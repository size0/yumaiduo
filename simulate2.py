def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="")
    args = ap.parse_args()

    cred = store.load_credentials()
    client = build_client(cred.get("model_api_key") or "")
    if not client.ready:
        print("✗ 没模型 Key")
        return 1

    cases = [c for c in Q if not args.only or args.only in c[0]]
    print("=" * 78)
    print(f"按类型模拟（{len(cases)} 条，真实原文）")
    print("=" * 78)

    last_cat = ""
    for i, (cat, msg, freq, our_line, seed) in enumerate(cases, 1):
        if cat != last_cat:
            print()
            print("━" * 78)
            print(f"  【{cat}】")
            print("━" * 78)
            last_cat = cat

        facts = Facts()
        for k, v in seed.items():
            facts.merge({k: v}, source="image")
        tools = Tools(provider="WANDA", quote_fn=fake_quote,
                      order_fn=fake_order, faq_fn=search_faq)
        history = ([{"role": "assistant", "content": our_line}]
                   if our_line else None)
        short = msg.replace("\n", " ⏎ ")[:76]
        print(f"\n  {i:>2}. 买家（×{freq}）：{short}")
        if our_line:
            print(f"      上文我们说的：{our_line[:60]}")
        try:
            turn = run_turn(client, tools, facts, msg, history=history)
        except Exception as exc:                            # noqa: BLE001
            print(f"      ✗ {type(exc).__name__}: {exc}")
            continue
        for m in (turn.messages or ["（★ 没回话）"]):
            for ln in m.splitlines():
                print(f"      {ln}")
        calls = [c["name"] + ("" if c["ok"] else f"✗{c['error_code']}")
                 for c in turn.calls]
        print(f"      → 工具：{calls or '（没调）'}"
              + ("   ★ 转人工" if turn.handoff else ""))
    print()
    return 0


if __name__ == "__main__":
    sys.exit(main())
